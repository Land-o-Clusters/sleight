test('the 500 ms watchdog restores while frame locking is pending and fences late input', async t => {
  t.mock.timers.enable({ apis: ['setTimeout'] });
  const f = fixture(); let finish, entered;
  const started = new Promise(resolve => { entered = resolve; });
  const pending = f.session.paste('text', async verify => {
    entered(); await new Promise(resolve => { finish = resolve; }); await verify(); assert.fail('no late input');
  });
  const failure = assert.rejects(pending, /500 ms.*clipboard restored/i);
  await started; t.mock.timers.tick(500);
  await new Promise(resolve => setImmediate(resolve));
  assert.deepEqual(f.board().items, restored(original));
  assert.equal(f.held(), true, 'retain the reservation until the input callback is collected');
  finish(); await failure; assert.equal(f.held(), false);
});
