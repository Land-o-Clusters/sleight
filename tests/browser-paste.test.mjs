const transient = { type: 'org.nspasteboard.TransientType', data: '' };
const restored = items => (items.length ? items : [[]]).map(reps => [...reps, transient]);
const original = [[{ type: 'public.png', data: 'AAEC' }, { type: 'public.rtf', data: 'e1xydGYxfQ==' }],
  [{ type: 'public.file-url', data: 'ZmlsZTovLy9maXh0dXJl' }]];
function fixture({ readError, writeError, restoreError, acquireError, releaseError, restoreTimeout = false, restoreFails = false, raceRecovery = false, raceClear = false, restoreDelayMs = 0, failRestores = 0, translated = false, raceStage = false, stageError } = {}) {
  let board = { count: 10, items: structuredClone(original) }, held = false, writes = 0, closed = false;
  const io = async request => {
    if (request.op === 'acquire') { if (acquireError || held) throw Error('busy'); held = true; return; }
    if (request.op === 'release') { held = false; if (releaseError) throw Error('release failed'); return; }
    if (request.op === 'read') { if (readError) throw Error(readError); return structuredClone(board); }
    assert.equal(request.op, 'write');
    if (stageError && writes === 0) { writes++; throw stageError; }
    if (raceStage && writes === 0) board = { count: board.count + 1, items: [[{ type: 'external', data: 'bmV3' }]] };
    if (request.expectedCount !== board.count) throw Object.assign(Error('ownership changed'), { clipboardMutation: false });
    writes++;
    if (writes > 1 && writes <= failRestores + 1) {
      board = { count: board.count + 1, items: [] };
      throw Object.assign(Error('helper timed out after clear'), { clipboardTimeout: true });
    }
    if (writes === 2 && restoreDelayMs) await new Promise(resolve => setTimeout(resolve, restoreDelayMs));
    if (restoreTimeout && writes === 2) {
      if (restoreTimeout === 'external') board = { count: board.count + 1, items: [[{ type: 'external', data: 'bmV3' }]] };
      if (restoreTimeout === 'cleared') board = { count: board.count + 1, items: [] };
      if (restoreTimeout === 'completed') board = { count: board.count + 1, items: structuredClone(request.items) };
      if (restoreTimeout === 'reordered') board = { count: board.count + 1, items: request.items.map(reps => [...reps].reverse()) };
      if (restoreTimeout === 'translated') board = { count: board.count + 1, items: request.items.map(reps => [...reps, { type: 'public.text', data: 'AA==' }]) };
      if (restoreTimeout === 'different bytes') board = { count: board.count + 1, items: request.items.map(reps => reps.map(rep => ({ ...rep, data: 'bmV3' }))) };
      if (restoreTimeout === 'different types') board = { count: board.count + 1, items: request.items.map(reps => reps.map(rep => ({ ...rep, type: 'external.' + rep.type }))) };
      throw Object.assign(Error('helper timed out'), { clipboardTimeout: true });
    }
    if (raceRecovery && writes === 3) {
      board = { count: board.count + 1, items: [[{ type: 'external', data: 'bmV3' }]] };
      throw Error('ownership changed');
    }
    if (raceClear && !request.items.length) {
      board = { count: board.count + 1, items: [[{ type: 'external', data: 'bmV3' }]] };
      throw Error('ownership changed');
    }
    if (restoreFails && request.items.length && writes > 1) throw Error('restore unavailable');
    board = { count: board.count + 1, items: structuredClone(request.items) };
    if (translated) board.items[0].push({ type: 'public.text', data: 'AA==' });
    if (writeError && writes === 1) throw Object.assign(Error('publish failed'), { clipboardMutation: true, clipboardCount: board.count });
    if (restoreError && writes === 2) throw Object.assign(Error('restore publish failed'), { clipboardMutation: true, clipboardCount: board.count });
    return { count: board.count };
  };
  io.close = async () => { closed = true; };
  return { session: createClipboardPasteSession(io), board: () => board, held: () => held, writes: () => writes, closed: () => closed,
    external() { board = { count: board.count + 1, items: [[{ type: 'external', data: 'bmV3' }]] }; } };
}

test('paste stages exact UTF-8 TSV once and restores all original clipboard items and formats', async () => {
  const f = fixture(), text = 'Name\tTotal\nZoë\t42\n\t'; let sends = 0;
  assert.equal(await f.session.paste(text, async () => {
    sends++; assert.equal(f.held(), true);
    assert.deepEqual(f.board().items, [[{ type: 'public.utf8-plain-text', data: Buffer.from(text).toString('base64') },
      transient, { type: 'org.nspasteboard.ConcealedType', data: '' }, { type: 'org.nspasteboard.AutoGeneratedType', data: '' }]]);
  }), 'clipboard restored');
  assert.equal(sends, 1); assert.equal(f.writes(), 2); assert.equal(f.held(), false);
  assert.deepEqual(f.board().items, restored(original));
});
