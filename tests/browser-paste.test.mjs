test('concurrent and closed paste sessions refuse; close waits for input and restoration', async () => {
  const f = fixture(); let release, started;
  const entered = new Promise(resolve => { started = resolve; });
  const run = f.session.paste('pending', async () => { started(); await new Promise(resolve => { release = resolve; }); });
  await entered;
  await assert.rejects(f.session.paste('second', () => assert.fail('no second input')), /busy/);
  const closing = f.session.close(); assert.equal(f.closed(), false); assert.equal(f.held(), true);
  release(); await run; await closing;
  assert.equal(f.closed(), true); assert.deepEqual(f.board().items, restored(original)); assert.equal(f.held(), false);
  await assert.rejects(f.session.paste('third', () => {}), /closed/);
});
