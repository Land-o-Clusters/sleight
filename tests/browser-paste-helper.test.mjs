import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import { createClipboardPasteSession } from '../plugins/sleight/lib/clipboard.mjs';
const source = readFileSync(new URL('../plugins/sleight/lib/clipboard.js', import.meta.url), 'utf8');
function fixture(chunks = [], { modern = true } = {}) {
  const data = bytes => ({ length: bytes.length, isNil: () => false, base64EncodedStringWithOptions: () => bytes.toString('base64') });
  const array = values => ({ get count() { return values.length; }, objectAtIndex: i => values[i], addObject: v => values.push(v), isNil: () => false });
  const board = { changeCount: 20, writes: 0, pasteboardItems: array([]), writeObjects: objects => { board.writes++; board.pasteboardItems = objects; return true; } };
  Object.defineProperty(board, 'clearContents', { get() { board.changeCount++; board.pasteboardItems = array([]); return board.changeCount; } });
  board.respondsToSelector = () => modern;
  board.prepareForNewContentsWithOptions = options => { board.options = options; return board.clearContents; };
  const written = [];
  const native = Object.assign(value => ({ dataUsingEncoding: () => value }), {
    NSMutableArray: { alloc: { get init() { return array([]); } } },
    NSPasteboardItem: { alloc: { get init() {
      const types = [], reps = new Map();
      return { types: array(types), dataForType: t => reps.get(t), setDataForType: (d, t) => { types.push(t); reps.set(t, d); return true; } };
    } } },
    NSData: { alloc: { initWithBase64EncodedStringOptions: value => data(Buffer.from(value, 'base64')) } },
    NSPasteboard: { generalPasteboard: board },
    NSString: { alloc: { initWithDataEncoding: input => input.text } },
    NSUTF8StringEncoding: 4, NSPasteboardContentsCurrentHostOnly: 1,
    NSFileHandle: {
      fileHandleWithStandardInput: {
        get availableData() { const text = chunks.shift() ?? ''; return { length: text.length, text }; },
        get readDataToEndOfFile() { const text = chunks.join(''); return { length: text.length, text }; },
      },
      fileHandleWithStandardOutput: { writeData: line => written.push(JSON.parse(line)) },
    },
  });
  const context = vm.createContext({ ObjC: { import: () => {}, unwrap: value => value }, $: native });
  vm.runInContext(source, context);
  return { board, context, read: maxBytes => JSON.parse(JSON.stringify(context.read(board, maxBytes))), write: r => context.write(board, r), array, data,
    serve: () => context.run(['--serve']), once: () => context.run([]), written };
}

const transient = { type: 'org.nspasteboard.TransientType', data: '' };
for (const modern of [true, false]) test(`helper publishes private paste and transient restore types (local API ${modern})`, async () => {
  const h = fixture([], { modern });
  const original = [[{ type: 'public.rtf', data: 'AAEC' }], [{ type: 'public.png', data: 'AwQF' }]];
  h.write({ expectedCount: 20, items: original });
  const requests = [];
  const io = async request => {
    requests.push(request);
    if (request.op === 'read') return h.read(request.maxBytes);
    if (request.op === 'write') return h.write(request);
  };
  const session = createClipboardPasteSession(io);
  assert.equal(await session.paste('private TSV', async () => {
    const reps = h.read().items[0];
    assert.deepEqual(reps.map(rep => rep.type), ['public.utf8-plain-text', 'org.nspasteboard.TransientType',
      'org.nspasteboard.ConcealedType', 'org.nspasteboard.AutoGeneratedType']);
    assert.equal(modern ? h.board.options : undefined, modern ? 1 : undefined);
  }), 'clipboard restored');
  assert.deepEqual(h.read().items, original.map(reps => [...reps, transient]));
  assert.equal(requests.find(request => request.op === 'read').maxBytes, 32 * 1024 * 1024);
  assert.equal(requests.filter(request => request.op === 'write').every(request => request.localOnly), true);
  await session.close();
});
test('a browser snapshot over 32 MiB refuses before staging or input, while generic helper reads retain 64 MiB', async () => {
  const h = fixture();
  const huge = { isNil: () => false, length: 32 * 1024 * 1024 + 1, base64EncodedStringWithOptions: () => '' };
  h.board.pasteboardItems = h.array([{ types: h.array(['public.png']), dataForType: () => huge }]);
  assert.throws(() => h.read(32 * 1024 * 1024), /32 MiB/);
  assert.doesNotThrow(() => h.read());
  const session = createClipboardPasteSession(async request => {
    if (request.op === 'read') return h.read(request.maxBytes);
    if (request.op === 'write') assert.fail('no staging');
  });
  await assert.rejects(session.paste('private', () => assert.fail('no input')), /32 MiB/);
  assert.equal(h.board.changeCount, 20); assert.equal(h.board.writes, 0);
});
test('a browser snapshot at exactly 32 MiB is allowed', () => {
  const h = fixture();
  const data = { isNil: () => false, length: 32 * 1024 * 1024, base64EncodedStringWithOptions: () => '' };
  h.board.pasteboardItems = h.array([{ types: h.array(['public.png']), dataForType: () => data }]);
  assert.doesNotThrow(() => h.read(32 * 1024 * 1024));
});
