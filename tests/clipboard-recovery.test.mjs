import { trackTemp } from '../scripts/temp-leftovers.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, realpathSync, rmSync, readdirSync, readFileSync, writeFileSync, statSync, chmodSync, symlinkSync, linkSync, openSync, ftruncateSync, closeSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { createClipboardPasteSession } from '../plugins/sleight/lib/clipboard.mjs';

const original = [[{ type: 'public.rtf', data: 'AAEC' }, { type: 'public.png', data: 'AwQF' }]];
const transient = { type: 'org.nspasteboard.TransientType', data: '' };
const staged = [[{ type: 'public.utf8-plain-text', data: 'cHJpdmF0ZQ==' }, transient,
  { type: 'org.nspasteboard.ConcealedType', data: '' }, { type: 'org.nspasteboard.AutoGeneratedType', data: '' }]];
const moduleURL = new URL('../plugins/sleight/lib/clipboard-recovery.mjs', import.meta.url);
const snapshots = directory => readdirSync(directory).filter(name => name.startsWith('snapshot-'));
async function fixture(t) {
  const api = await import(moduleURL);
  const root = trackTemp(mkdtempSync(join(realpathSync(tmpdir()), 'sleight-recovery-')));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const directory = join(root, 'clipboard'), store = api.createClipboardSnapshotStore({ directory,
    bootSession: () => 'fixture-boot', excludeFromBackup: () => {} });
  let board = { count: 7, items: structuredClone(staged) }, held = false, writes = 0;
  const io = async request => {
    if (request.op === 'acquire') { assert.equal(held, false); held = true; return; }
    if (request.op === 'release') { held = false; return; }
    assert.equal(held, true);
    if (request.op === 'read') return structuredClone(board);
    assert.equal(request.op, 'write'); assert.equal(request.expectedCount, board.count);
    writes++; board = { count: board.count + 1, items: structuredClone(request.items) }; return { count: board.count };
  };
  io.snapshotStore = store;
  return { ...api, root, directory, store, io, board: () => board, held: () => held, writes: () => writes,
    setBoard(items) { board = { count: board.count + 1, items: structuredClone(items) }; } };
}
test('snapshot is durable and private before staging, then deleted only after restoration', async t => {
  const f = await fixture(t); f.setBoard(original);
  const session = createClipboardPasteSession(f.io);
  await session.paste('private', async () => {
    const names = snapshots(f.directory); assert.equal(names.length, 1);
    const saved = statSync(join(f.directory, names[0]));
    assert.equal(saved.mode & 0o777, 0o600); assert.equal(saved.uid, process.getuid());
    assert.ok(saved.size <= 32 * 1024 * 1024);
    assert.deepEqual(f.store.list()[0].record.original, original);
  });
  assert.deepEqual(f.board().items, [[...original[0], transient]]);
  assert.deepEqual(snapshots(f.directory), []);
});
for (const contents of ['staged', 'empty', 'translated']) test('startup restores crash leftovers: ' + contents, async t => {
  const f = await fixture(t);
  f.store.save({ original, staged });
  if (contents === 'empty') f.setBoard([]);
  if (contents === 'translated') f.setBoard([[...staged[0], { type: 'public.text', data: 'eA==' }]]);
  await f.recoverClipboardSnapshots(f.io);
  assert.deepEqual(f.board().items, [[...original[0], transient]]);
  assert.deepEqual(snapshots(f.directory), []); assert.equal(f.held(), false);
});
test('startup discards a leftover after a third-party copy and logs no clipboard data', async t => {
  const f = await fixture(t), notices = [];
  f.store.save({ original, staged }); f.setBoard([[{ type: 'other', data: 'bmV3' }]]);
  await f.recoverClipboardSnapshots(f.io, { notice: code => notices.push(code) });
  assert.deepEqual(f.board().items, [[{ type: 'other', data: 'bmV3' }]]); assert.equal(f.writes(), 0);
  assert.deepEqual(snapshots(f.directory), []); assert.deepEqual(notices, ['CLIPBOARD_SNAPSHOT_DISCARDED_CHANGED']);
});
test('startup leaves a live owner and its snapshot untouched when the reservation is busy', async t => {
  const f = await fixture(t); f.store.save({ original, staged });
  const busy = async () => { throw Error('busy'); };
  busy.snapshotStore = { ...f.store, list: () => assert.fail('do not materialize an active owner snapshot') };
  await f.recoverClipboardSnapshots(busy);
  assert.equal(snapshots(f.directory).length, 1); assert.equal(f.writes(), 0);
});
test('failed restoration keeps the persisted snapshot for the next startup', async t => {
  const f = await fixture(t); f.setBoard(original);
  let writes = 0;
  const io = async request => {
    if (request.op === 'write' && ++writes > 1) { f.setBoard([]); throw Error('helper failed after clear'); }
    return f.io(request);
  }; io.snapshotStore = f.store;
  await assert.rejects(createClipboardPasteSession(io).paste('private', async () => {}), /restoration unconfirmed/);
  assert.equal(snapshots(f.directory).length, 1);
  await f.recoverClipboardSnapshots(f.io);
  assert.deepEqual(f.board().items, [[...original[0], transient]]); assert.deepEqual(snapshots(f.directory), []);
});
test('recovery stops at 30 seconds with each helper request bounded by the remaining time', async t => {
  const f = await fixture(t); f.store.save({ original, staged });
  let now = 0, writes = 0, fresh = 0;
  const io = async request => {
    if (request.op === 'write') { assert.ok(request.timeoutMs <= 30000 - now); writes++; now += 16000; throw Error('timeout'); }
    return f.io(request);
  }; io.snapshotStore = f.store; io.restart = async () => { fresh++; };
  await f.recoverClipboardSnapshots(io, { now: () => now });
  assert.equal(writes, 2); assert.equal(fresh, 2);
  assert.equal(snapshots(f.directory).length, 1); assert.equal(f.held(), false);
});
test('the last lost restore acknowledgment still deletes a confirmed snapshot', async t => {
  const f = await fixture(t); f.store.save({ original, staged });
  let writes = 0;
  const io = async request => {
    if (request.op === 'write') {
      if (++writes === 5) await f.io(request);
      throw Error('lost acknowledgment');
    }
    return f.io(request);
  }; io.snapshotStore = f.store;
  await f.recoverClipboardSnapshots(io);
  assert.equal(writes, 5); assert.deepEqual(snapshots(f.directory), []);
  assert.deepEqual(f.board().items, [[...original[0], transient]]);
});
test('snapshot store refuses symlinks, hardlinks, permissive files and files over 32 MiB', async t => {
  const f = await fixture(t);
  for (const kind of ['symlink', 'hardlink', 'mode', 'size']) {
    const token = f.store.save({ original, staged });
    const file = join(f.directory, token.name);
    if (kind === 'symlink') { const target = join(f.root, 'target'); writeFileSync(target, 'private'); rmSync(file); symlinkSync(target, file); }
    if (kind === 'hardlink') linkSync(file, join(f.root, 'alias'));
    if (kind === 'mode') chmodSync(file, 0o644);
    if (kind === 'size') { const fd = openSync(file, 'r+'); ftruncateSync(fd, 32 * 1024 * 1024 + 1); closeSync(fd); }
    assert.equal(f.store.list()[0].code, 'CLIPBOARD_SNAPSHOT_SKIPPED_UNSAFE');
    assert.throws(() => f.store.remove(token), /snapshot|Snapshot|ELOOP/);
    rmSync(file); if (kind === 'hardlink') rmSync(join(f.root, 'alias'));
    assert.ok(token);
  }
});
test('large binary snapshots fit the disk cap without base64 expansion; excess metadata refuses before stage', async t => {
  const f = await fixture(t);
  const large = [[{ type: 'public.png', data: Buffer.alloc(31 * 1024 * 1024, 0xa5).toString('base64') }]];
  const token = f.store.save({ original: large, staged });
  const file = join(f.directory, token.name);
  assert.ok(statSync(file).size < 32 * 1024 * 1024);
  assert.deepEqual(f.store.list()[0].record.original, large); f.store.remove(token);
  f.setBoard([[{ type: 'public.png', data: Buffer.alloc(32 * 1024 * 1024).toString('base64') }]]);
  await assert.rejects(createClipboardPasteSession(f.io).paste('private', () => assert.fail('no input')), /32 MiB/);
  assert.equal(f.writes(), 0); assert.deepEqual(snapshots(f.directory), []);
});
test('a truncated file is discarded and logged before clipboard reads', async t => {
  const f = await fixture(t), notices = [];
  const token = f.store.save({ original, staged });
  const file = join(f.directory, token.name); writeFileSync(file, Buffer.from([0, 1]));
  const io = request => {
    if (request.op === 'read' || request.op === 'write') assert.fail('partial persistence precedes staging');
    return f.io(request);
  }; io.snapshotStore = f.store;
  await f.recoverClipboardSnapshots(io, { notice: code => notices.push(code) });
  assert.deepEqual(snapshots(f.directory), []); assert.deepEqual(notices, ['CLIPBOARD_SNAPSHOT_DISCARDED_INVALID']);
});
test('staged bytes without the transient marker cannot overwrite a newer clipboard on startup', async t => {
  const f = await fixture(t), notices = [];
  f.store.save({ original, staged }); f.setBoard([staged[0].filter(rep => rep.type !== transient.type)]);
  await f.recoverClipboardSnapshots(f.io, { notice: code => notices.push(code) });
  assert.equal(f.writes(), 0); assert.deepEqual(snapshots(f.directory), []);
  assert.deepEqual(notices, ['CLIPBOARD_SNAPSHOT_DISCARDED_CHANGED']);
});
test('an unsafe snapshot directory prevents stage and input', async t => {
  const f = await fixture(t), outside = join(f.root, 'outside');
  const { mkdirSync } = await import('node:fs'); mkdirSync(outside); symlinkSync(outside, f.directory);
  f.setBoard(original);
  await assert.rejects(createClipboardPasteSession(f.io).paste('private', () => assert.fail('no paste')), /snapshot|Snapshot/);
  assert.deepEqual(f.board().items, original); assert.equal(f.writes(), 0); assert.deepEqual(readdirSync(outside), []);
});
test('a worker killed after stage leaves a recoverable snapshot on disk', async t => {
  const f = await fixture(t), boardPath = join(f.root, 'board.json');
  const child = spawnSync(process.execPath, [new URL('./fixtures/clipboard-crash.mjs', import.meta.url).pathname, f.directory, boardPath],
    { encoding: 'utf8', timeout: 5000 });
  assert.equal(child.signal, 'SIGKILL', child.stderr);
  f.setBoard(JSON.parse(readFileSync(boardPath, 'utf8')).items);
  assert.equal(snapshots(f.directory).length, 1);
  await f.recoverClipboardSnapshots(f.io);
  assert.deepEqual(f.board().items, [[...original[0], transient]]); assert.deepEqual(snapshots(f.directory), []);
});
